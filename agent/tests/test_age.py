import pytest
from dose_agent.age import age_in_months, format_age


@pytest.mark.parametrize("dob,on,want", [
    ("2026-07-31", "2026-10-16", "11 w"),
    ("2026-10-16", "2026-10-16", "0 w"),
    ("2026-09-04", "2026-10-16", "6 w"),
    ("2026-04-16", "2026-10-16", "6 m"),
    ("2026-04-17", "2026-10-16", "26 w"),
    ("2024-10-17", "2026-10-16", "23 m"),
    ("2024-10-16", "2026-10-16", "2 y"),
    ("2022-02-10", "2026-10-16", "4 y 8 m"),
    (None, "2026-10-16", None),
    ("2026-10-17", "2026-10-16", None),
    ("garbage", "2026-10-16", None),
    ("26-07-2026", "2026-09-06", None),
    ("2026-03-31", "2026-09-30", "26 w"),
    ("2026-03-31", "2026-10-01", "6 m"),
    ("2024-02-29", "2026-02-28", "23 m"),
    ("2024-02-29", "2026-03-01", "2 y"),
])
def test_format_age(dob, on, want):
    assert format_age(dob, on) == want


def test_months():
    assert age_in_months("2022-02-10", "2026-10-16") == 56
    assert age_in_months(None, "2026-10-16") is None
